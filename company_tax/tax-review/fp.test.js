'use strict';
// FP센터 데이터·계산 모듈 검증 — 실행: node fp.test.js
//
// 기대값 산출 근거 (원칙 제3조):
//   · 거리는 하버사인 수식으로, 지도 좌표는 투영 산식으로 직접 계산했다.
//   · 구현을 실행해 얻은 값을 기대값으로 삼지 않았다. 산출 과정은 각 단언 옆 주석에 남긴다.

const assert = require('node:assert/strict');
const {
  FP_SOURCE, CENTERS, fpExpiryStatus,
  distanceKm, nearestCenters, inKorea,
  MAP_BOUNDS, KOREA_OUTLINE, JEJU, mapSize, projectPoint,
} = require('./fp.js');

let n = 0;
const ok = (cond, msg) => { assert.ok(cond, msg); n += 1; };
const eq = (a, b, msg) => { assert.equal(a, b, msg); n += 1; };
const near = (a, b, tol, msg) => {
  assert.ok(Math.abs(a - b) < tol, msg + ' — 기대 ' + b + ' ± ' + tol + ', 실제 ' + a);
  n += 1;
};

// ══════════════════════════ 데이터 무결성 ══════════════════════════

eq(CENTERS.length, 8, 'FP센터는 8곳이다');
eq(new Set(CENTERS.map((c) => c.이름)).size, 8, '센터 이름이 중복되지 않는다');

CENTERS.forEach((c) => {
  ok(c.이름 && c.전화 && c.주소, c.이름 + ': 필수 필드 누락');
  // 좌표가 뒤바뀌거나 0이면 여기서 걸린다.
  ok(c.lat > 33 && c.lat < 39, c.이름 + ': 위도 범위 이탈 ' + c.lat);
  ok(c.lng > 124 && c.lng < 132, c.이름 + ': 경도 범위 이탈 ' + c.lng);
  ok(/^0\d{1,2}-\d{3,4}-\d{4}$/.test(c.전화), c.이름 + ': 전화번호 형식 ' + c.전화);
});

eq(FP_SOURCE.심의번호, '25-3281', '준법감시 심의번호');
eq(FP_SOURCE.유효기간.만료, '2026-10-27', '준법감시 만료일');

// ══════════════════════════ 준법감시 유효기간 ══════════════════════════
// 만료일 2026-10-27, 경고 임계 60일.
// 2026-08-27 기준 → 8/28~8/31 4일 + 9월 30일 + 10/1~10/27 27일 = 61일
eq(fpExpiryStatus('2026-08-27').남은일수, 61, '2026-08-27 → 61일');
eq(fpExpiryStatus('2026-08-27').경고, false, '61일 전에는 경고하지 않는다');

// 2026-08-28 기준 → 3 + 30 + 27 = 60일
eq(fpExpiryStatus('2026-08-28').남은일수, 60, '2026-08-28 → 60일');
eq(fpExpiryStatus('2026-08-28').경고, true, '60일 전부터 경고한다');

eq(fpExpiryStatus('2026-10-27').만료됨, false, '만료 당일은 아직 유효하다');
eq(fpExpiryStatus('2026-10-27').남은일수, 0, '만료 당일은 0일');
eq(fpExpiryStatus('2026-10-28').만료됨, true, '만료 다음날부터 만료됨');
eq(fpExpiryStatus('2026-10-28').남은일수, -1, '만료 다음날은 -1일');

// ══════════════════════════ 거리 ══════════════════════════
// 지구 반지름 6371km. 위도 1도 = 6371 × (π/180) = 6371 × 0.0174533 = 111.195km
// 경도차가 0이므로 하버사인에는 위도차 항만 남는다.
near(distanceKm(0, 0, 1, 0), 111.195, 0.01, '위도 1도는 111.195km');
// 적도에서는 경도 1도도 같다 (cos 0 = 1)
near(distanceKm(0, 0, 0, 1), 111.195, 0.01, '적도의 경도 1도는 111.195km');
eq(distanceKm(37.5, 127.0, 37.5, 127.0), 0, '같은 좌표는 0km');
eq(
  distanceKm(37.570962, 126.981438, 35.149733, 129.058779),
  distanceKm(35.149733, 129.058779, 37.570962, 126.981438),
  '거리는 방향에 무관하다'
);

// 서울FP센터(37.570962, 126.981438) ↔ 부산FP센터(35.149733, 129.058779)
//   Δφ = -2.421229° = -0.0422540 rad,  Δλ = 2.077341° = 0.0362565 rad
//   sin²(Δφ/2) = (-0.0211254)² = 0.00044628
//   cosφ1·cosφ2 = 0.792746 × 0.817656 = 0.648193
//   sin²(Δλ/2) = (0.0181270)² = 0.00032859  →  0.648193 × 0.00032859 = 0.00021299
//   a = 0.00065927,  √a = 0.0256763,  c = 2·asin(√a) = 0.0513582
//   d = 6371 × 0.0513582 = 327.20 km
near(distanceKm(37.570962, 126.981438, 35.149733, 129.058779), 327.20, 1, '서울↔부산 약 327km');

// ══════════════════════════ 가까운 순 정렬 ══════════════════════════
// 강남역 부근 (37.4979, 127.0276) 손계산.
// 위도 1도 = 111.195km, 경도 1도 = 111.195 × cos37.47° = 88.26km
//   강남FP센터  약 0.2km   (Δφ 0.001156° → 0.13km,  Δλ 0.001896° → 0.17km)
//   서울FP센터  약 9.1km   (Δφ 0.073062° → 8.12km,  Δλ 0.046162° → 4.07km)
//   경원FP센터  약 24.7km  (Δφ 0.222269° → 24.71km, 경도차 0.003° 무시 가능)
//   경인FP센터  약 29.0km  (Δφ 0.047641° → 5.30km,  Δλ 0.322536° → 28.46km)
const 강남기준 = nearestCenters(37.4979, 127.0276, CENTERS);
eq(강남기준.length, 3, '기본 반환 개수는 3');
assert.deepEqual(
  강남기준.map((c) => c.이름),
  ['강남FP센터', '서울FP센터', '경원FP센터'],
  '강남역 기준 가까운 순'
);
n += 1;
ok(강남기준[0].거리km < 1, '강남FP센터는 1km 이내');
ok(강남기준[0].거리km < 강남기준[1].거리km, '오름차순 정렬');
ok(강남기준[1].거리km < 강남기준[2].거리km, '오름차순 정렬');
eq(강남기준[0].전화, '02-3451-1700', '원본 필드가 보존된다');

// 제주시청 부근 (33.4996, 126.5312) 손계산.
//   호남FP센터  약 187km  (Δφ 1.653692° → 183.88km, Δλ 0.378821° → 34.80km)
//   부산FP센터  약 296km  (Δφ 1.650133° → 183.49km, Δλ 2.527579° → 232.18km)
// 3·4위(대구 약 324km / 충청 약 327km)는 손계산 오차 범위 안에서 갈리므로 단언하지 않는다.
const 제주기준 = nearestCenters(33.4996, 126.5312, CENTERS);
eq(제주기준[0].이름, '호남FP센터', '제주에서 가장 가까운 곳은 호남');
eq(제주기준[1].이름, '부산FP센터', '제주에서 두 번째는 부산');
ok(제주기준[0].거리km > 100, '제주에는 센터가 없으므로 100km를 넘는다');

eq(nearestCenters(37.4979, 127.0276, CENTERS, 1).length, 1, '개수 지정 1');
eq(nearestCenters(37.4979, 127.0276, CENTERS, 8).length, 8, '개수 지정 8');
eq(nearestCenters(37.4979, 127.0276, CENTERS, 99).length, 8, '있는 만큼만 반환한다');
assert.deepEqual(nearestCenters(37.4979, 127.0276, []), [], '빈 배열');
n += 1;

const 원본순서 = CENTERS.map((c) => c.이름);
nearestCenters(35.1, 129.0, CENTERS);
assert.deepEqual(CENTERS.map((c) => c.이름), 원본순서, '입력 배열을 정렬하지 않는다');
n += 1;

// ══════════════════════════ 국내 여부 ══════════════════════════
ok(inKorea(37.5, 127.0), '서울은 국내');
ok(inKorea(33.4996, 126.5312), '제주는 국내');
ok(!inKorea(35.68, 139.76), '도쿄는 국내가 아니다');
ok(!inKorea(0, 0), '적도 0,0은 국내가 아니다');

// ══════════════════════════ 개략도 투영 ══════════════════════════
// 가로세로 비 = 세로 거리 ÷ 가로 거리
//   세로 = (38.65 - 33.05) × 111.195 = 5.60 × 111.195 = 622.692km
//   가로 = (129.85 - 125.95) × 111.195 × cos(35.85°) = 3.90 × 111.195 × 0.81054 = 351.49km
//   비율 = 622.692 ÷ 351.49 = 1.7716  →  폭 280이면 높이 496.0
const size = mapSize(280);
eq(size.w, 280, '지도 폭은 인자 그대로');
near(size.h, 496.0, 1.0, '폭 280일 때 높이는 약 496');

// 서울FP센터(37.570962, 126.981438)
//   x = (126.981438 - 125.95) ÷ 3.90 × 280 = 0.264471 × 280 = 74.05
//   y = (38.65 - 37.570962) ÷ 5.60 × 496.05 = 0.192685 × 496.05 = 95.58
const 서울점 = projectPoint(37.570962, 126.981438, size);
near(서울점.x, 74.05, 0.5, '서울 핀 x');
near(서울점.y, 95.58, 0.6, '서울 핀 y');

// 부산FP센터(35.149733, 129.058779)
//   x = (129.058779 - 125.95) ÷ 3.90 × 280 = 0.797123 × 280 = 223.19
//   y = (38.65 - 35.149733) ÷ 5.60 × 496.05 = 0.625048 × 496.05 = 310.06
const 부산점 = projectPoint(35.149733, 129.058779, size);
near(부산점.x, 223.19, 0.5, '부산 핀 x');
near(부산점.y, 310.06, 0.6, '부산 핀 y');

ok(서울점.x < 부산점.x, '부산은 서울보다 동쪽(오른쪽)이다');
ok(서울점.y < 부산점.y, '북쪽이 위 — 서울의 y가 더 작다');

// 모든 핀과 해안선이 지도 안에 들어온다. 벗어나면 경계 설정이 잘못된 것이다.
CENTERS.forEach((c) => {
  const p = projectPoint(c.lat, c.lng, size);
  ok(p.x >= 0 && p.x <= size.w && p.y >= 0 && p.y <= size.h, c.이름 + ': 지도 밖 ' + p.x + ',' + p.y);
});
KOREA_OUTLINE.forEach((pt, i) => {
  ok(
    pt[0] > MAP_BOUNDS.lat0 && pt[0] < MAP_BOUNDS.lat1 && pt[1] > MAP_BOUNDS.lng0 && pt[1] < MAP_BOUNDS.lng1,
    '해안선 ' + i + '번 점이 경계를 벗어남 ' + pt
  );
});
ok(KOREA_OUTLINE.length >= 20, '해안선이 형태를 알아볼 만큼 촘촘하다');

// 제주 반경 — 남북 31km의 절반 15.5km ÷ 111.195 = 0.13939도
//              동서 73km의 절반 36.5km ÷ (111.195 × cos33.38°=0.83501 → 92.848) = 0.39311도
near(JEJU.위도반경, 0.13939, 0.0002, '제주 위도 반경(도)');
near(JEJU.경도반경, 0.39311, 0.0005, '제주 경도 반경(도)');
ok(
  JEJU.lat > MAP_BOUNDS.lat0 && JEJU.lat < CENTERS[7].lat,
  '제주는 지도 안이면서 호남FP센터보다 남쪽이다'
);

// ══════════════════════════ 독립 페이지 사본과의 대조 ══════════════════════════
// company_tax/fp-center/ 는 같은 데이터·같은 거리 계산을 가진 독립 조회 페이지다.
// 소유자 결정(2026-08-21)에 따라 이 통합본을 메인으로 쓰고 독립 페이지도 함께 유지한다.
//
// 문제는 준법감시필 25-3281 데이터가 두 곳에 복제되어 있다는 점이다. 만료(2026-10-27)나
// 센터 이전 시 한쪽만 고치면 조용히 어긋난다. 사람이 두 파일을 기억하는 대신 여기서 잡는다.
// 독립 페이지를 지우면 이 대조는 건너뛴다 — 사본이 없으면 어긋날 것도 없다.
let mirror = null;
try {
  mirror = {
    centers: require('../fp-center/centers.js'),
    nearest: require('../fp-center/nearest.js'),
  };
} catch (e) {
  console.log('  (독립 페이지 사본이 없어 대조를 건너뜁니다)');
}

if (mirror !== null) {
  eq(mirror.centers.CENTERS.length, CENTERS.length, '사본의 센터 수가 같다');
  eq(mirror.centers.SOURCE.심의번호, FP_SOURCE.심의번호, '사본의 심의번호가 같다');
  eq(mirror.centers.SOURCE.유효기간.만료, FP_SOURCE.유효기간.만료, '사본의 만료일이 같다');

  CENTERS.forEach((c, i) => {
    const m = mirror.centers.CENTERS[i];
    ['이름', '전화', '주소', 'lat', 'lng'].forEach((k) => {
      eq(String(m[k]), String(c[k]), '사본 ' + c.이름 + '.' + k + ' 일치');
    });
  });

  // 거리 계산은 두 구현이 같은 값을 내야 한다. 8곳 전 조합을 대조한다.
  CENTERS.forEach((p) => CENTERS.forEach((q) => {
    eq(
      mirror.nearest.distanceKm(p.lat, p.lng, q.lat, q.lng),
      distanceKm(p.lat, p.lng, q.lat, q.lng),
      '사본 거리 ' + p.이름 + '→' + q.이름
    );
  }));

  // 유효기간 판정 경계도 같아야 한다.
  ['2026-08-27', '2026-08-28', '2026-10-27', '2026-10-28'].forEach((day) => {
    const m = mirror.centers.expiryStatus(day);
    const t = fpExpiryStatus(day);
    eq(m.남은일수, t.남은일수, '사본 남은일수 ' + day);
    eq(m.경고, t.경고, '사본 경고 ' + day);
    eq(m.만료됨, t.만료됨, '사본 만료 ' + day);
  });
}

console.log('FP센터 모듈: ' + n + '개 단언 통과'
  + (mirror === null ? '' : ' (독립 페이지 사본 대조 포함)'));
